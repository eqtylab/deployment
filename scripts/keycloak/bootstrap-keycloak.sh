#!/usr/bin/env bash
set -e

SOURCE="${BASH_SOURCE[0]}"
while [ -h "$SOURCE" ]; do SOURCE="$(readlink "$SOURCE")"; done
ROOTDIR="$(cd -P "$(dirname "$SOURCE")/../.." && pwd)"

# shellcheck source=../helpers/output.sh
source "$ROOTDIR/scripts/helpers/output.sh"
# shellcheck source=../helpers/assert.sh
source "$ROOTDIR/scripts/helpers/assert.sh"

# Function to display usage
usage() {
  echo -e "\
Bootstrap Keycloak realm, clients, scopes, and users for the Guardian Platform

Usage: $0 -f <values-file> [options]
  -c, --chart-dir <dir>           Chart directory (default: $CHART_DIR)
  -f, --values <file>             Helm values file for keycloak-bootstrap chart (required)
  -h, --help                      Show this help message
  -l, --keycloak-selector <sel>   Label selector for the Keycloak pod (default: $KEYCLOAK_SELECTOR)
  -n, --namespace <namespace>     Kubernetes namespace (required)
  -r, --release <name>            Helm release name (default: $BOOTSTRAP_RELEASE)

Examples:
  $0 -f $CHART_DIR/examples/values.yaml -n guardian
  $0 -f my-values.yaml --namespace guardian-stag
"
}

# Verify Keycloak is running and required secrets exist
check_prerequisites() {
  print_warn "Checking prerequisites..."

  # Check if Keycloak pod is running
  local keycloak_ready
  keycloak_ready=$(kubectl get pod -l "$KEYCLOAK_SELECTOR" -n "$NAMESPACE" -o jsonpath='{.items[0].status.conditions[?(@.type=="Ready")].status}' 2>/dev/null)
  if [ "$keycloak_ready" != "True" ]; then
    print_error "Keycloak pod ($KEYCLOAK_SELECTOR) is not ready"
    kubectl get pod -l "$KEYCLOAK_SELECTOR" -n "$NAMESPACE"
    exit 1
  fi
  print_info "Keycloak is running"

  # Check required secrets
  # The bootstrap job mounts the Keycloak admin secret, and the platform admin
  # secret when users.admin.enabled is true (default)
  # Backend/worker client secrets are auto-generated by Keycloak
  local required_secrets=("$KEYCLOAK_ADMIN_SECRET")
  if [ "$PLATFORM_ADMIN_ENABLED" != "false" ]; then
    required_secrets+=("$PLATFORM_ADMIN_SECRET")
  fi
  local missing_secrets=()
  for secret in "${required_secrets[@]}"; do
    if ! kubectl get secret "$secret" -n "$NAMESPACE" &>/dev/null; then
      missing_secrets+=("$secret")
    fi
  done

  if [ ${#missing_secrets[@]} -gt 0 ]; then
    print_error "Missing required secrets:"
    printf '%s\n' "${missing_secrets[@]}"
    echo ""
    echo "Create them with:"
    echo "  kubectl create secret generic $KEYCLOAK_ADMIN_SECRET --from-literal=$KEYCLOAK_ADMIN_KEY=<admin-password> -n $NAMESPACE"
    if [ "$PLATFORM_ADMIN_ENABLED" != "false" ]; then
      echo "  kubectl create secret generic $PLATFORM_ADMIN_SECRET --from-literal=$PLATFORM_ADMIN_KEY=<platform-admin-password> -n $NAMESPACE"
    fi
    exit 1
  fi
  print_info "All required secrets exist"
}

# Deploy the keycloak-bootstrap Helm chart, which waits for the bootstrap job
run_bootstrap() {
  # Clean up any existing bootstrap jobs
  print_warn "Cleaning up any existing bootstrap jobs..."
  kubectl delete job -l app.kubernetes.io/instance="$BOOTSTRAP_RELEASE" -n "$NAMESPACE" --ignore-not-found

  # Run the bootstrap
  print_warn "Running Keycloak bootstrap..."

  if ! helm upgrade --install "$BOOTSTRAP_RELEASE" "$CHART_DIR" \
    -n "$NAMESPACE" \
    -f "$VALUES_FILE" \
    --wait \
    --timeout 10m; then
    print_error "Bootstrap job failed or timed out"
    kubectl logs -l app.kubernetes.io/instance="$BOOTSTRAP_RELEASE" -n "$NAMESPACE" --tail=50 || true
    exit 1
  fi

  # Get the job name
  local job_name
  job_name=$(kubectl get job -l app.kubernetes.io/instance="$BOOTSTRAP_RELEASE" -n "$NAMESPACE" -o jsonpath='{.items[0].metadata.name}' 2>/dev/null)

  if [ -z "$job_name" ]; then
    print_error "Bootstrap job not found"
    exit 1
  fi

  print_info "Bootstrap job $job_name completed"

  # Show logs
  echo ""
  print_warn "Bootstrap logs (last 20 lines):"
  kubectl logs job/"$job_name" -n "$NAMESPACE" --tail=20

  # Cleanup completed job
  echo ""
  print_warn "Cleaning up completed job..."
  kubectl delete job "$job_name" -n "$NAMESPACE" --ignore-not-found
}

# Read a key from the values file with yq, falling back to the chart default
values_get() {
  local value
  value=$(yq "$1 // \"\"" "$VALUES_FILE" 2>/dev/null)
  echo "${value:-$2}"
}

# Display credentials, OAuth clients, and Keycloak URLs
show_summary() {
  local realm frontend_client backend_client worker_client backend_roles
  realm=$(values_get '.keycloak.realm.name' guardian)
  frontend_client=$(values_get '.clients.frontend.clientId' guardian-platform-frontend)
  backend_client=$(values_get '.clients.backend.clientId' guardian-platform-backend)
  worker_client=$(values_get '.clients.worker.clientId' governance-worker)
  backend_roles=$(values_get '([.clients.backend.serviceAccountRoles[]? | (.roles | join(", ")) + " (" + .clientId + ")"] | join("; "))' "query-users, view-users (realm-management)")

  echo ""
  print_info "Bootstrap Complete!"
  echo ""
  echo "Keycloak URLs:"
  echo "- Admin Console: https://DOMAIN/keycloak/admin"
  echo "- Platform Realm: https://DOMAIN/keycloak/admin/${realm}/console"
  echo ""

  # Show where the credentials are stored
  echo "Keycloak Admin (master realm):"
  echo "  Username: $(values_get '.keycloak.adminUsername' admin)"
  echo "  Password: kubectl get secret $KEYCLOAK_ADMIN_SECRET -n $NAMESPACE -o jsonpath='{.data.$KEYCLOAK_ADMIN_KEY}' | base64 -d"
  echo ""

  if [ "$PLATFORM_ADMIN_ENABLED" != "false" ]; then
    echo "Platform Admin (${realm} realm):"
    echo "  Username: $(values_get '.users.admin.username' platform-admin)"
    echo "  Password: kubectl get secret $PLATFORM_ADMIN_SECRET -n $NAMESPACE -o jsonpath='{.data.$PLATFORM_ADMIN_KEY}' | base64 -d"
    echo ""
  fi

  echo "OAuth Clients:"
  echo "- Frontend: ${frontend_client} (public client)"
  echo "- Backend: ${backend_client} (confidential with service account)"
  echo "- Worker: ${worker_client} (service account only)"
  echo ""
  echo "Backend service account roles: ${backend_roles}"

  echo ""
  print_info "Bootstrap process completed!"
}

# Configurable parameters
NAMESPACE=""
VALUES_FILE=""
CHART_DIR="$ROOTDIR/charts/keycloak-bootstrap"
BOOTSTRAP_RELEASE="keycloak-bootstrap"
KEYCLOAK_SELECTOR="app=keycloak"

# Parse arguments
while [[ $# -gt 0 ]]; do
  case $1 in
  -c | --chart-dir)
    CHART_DIR="$2"
    shift 2
    ;;
  -f | --values)
    VALUES_FILE="$2"
    shift 2
    ;;
  -h | --help)
    usage
    exit 0
    ;;
  -l | --keycloak-selector)
    KEYCLOAK_SELECTOR="$2"
    shift 2
    ;;
  -n | --namespace)
    NAMESPACE="$2"
    shift 2
    ;;
  -r | --release)
    BOOTSTRAP_RELEASE="$2"
    shift 2
    ;;
  *)
    print_error "Unknown option: $1"
    usage
    exit 1
    ;;
  esac
done

# Validate prerequisites
assert_is_installed "helm"
assert_is_installed "kubectl"
assert_is_installed "yq"
if ! yq --version 2>&1 | grep -q mikefarah; then
  print_error "yq must be mikefarah/yq v4 (https://github.com/mikefarah/yq)"
  exit 1
fi

# Validate required arguments
assert_not_empty "namespace" "$NAMESPACE" "Use -n or --namespace to provide a namespace."
assert_not_empty "values-file" "$VALUES_FILE" "Use -f or --values to provide a Helm values file."

# Validate path to file exists
assert_path_exists "chart-dir" "$CHART_DIR"

if [ ! -f "$VALUES_FILE" ]; then
  print_error "Values file not found: $VALUES_FILE"
  exit 1
fi

# Secret names and keys the bootstrap job reads, from the values file
KEYCLOAK_ADMIN_SECRET=$(values_get '.keycloak.adminPasswordSecret.name' keycloak-admin)
KEYCLOAK_ADMIN_KEY=$(values_get '.keycloak.adminPasswordSecret.key' password)
PLATFORM_ADMIN_ENABLED=$(values_get '.users.admin.enabled | select(. != null) | tostring' true)
PLATFORM_ADMIN_SECRET=$(values_get '.users.admin.secretName' platform-admin)
PLATFORM_ADMIN_KEY=$(values_get '.users.admin.secretKey' password)

echo -e "\
Namespace:    $NAMESPACE
Release:      $BOOTSTRAP_RELEASE
Chart:        $CHART_DIR
Values:       $VALUES_FILE

This will create:
- Platform realm
- Platform admin user
- Three OAuth clients:
  - Frontend (public client)
  - Backend (confidential with service account)
  - Worker (service account only)
- Custom authorization scopes
- Service account roles for backend client
"

# Verify Keycloak
check_prerequisites
# Deploy the keycloak-bootstrap
run_bootstrap
# Display outputs
show_summary
