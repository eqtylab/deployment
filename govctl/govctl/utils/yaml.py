"""YAML utilities for govctl."""

import re
from typing import Any

import yaml

from govctl.core.models import PlatformConfig


class LiteralStr(str):
    """String subclass that signals literal block style in YAML."""


class QuotedStr(str):
    """String subclass for markers that must remain single-quoted in YAML."""


def _quoted_representer(dumper: yaml.Dumper, data: str) -> yaml.ScalarNode:
    return dumper.represent_scalar("tag:yaml.org,2002:str", data, style="'")


def _literal_representer(dumper: yaml.Dumper, data: str) -> yaml.ScalarNode:
    """Represent multiline strings using literal block style (|)."""
    return dumper.represent_scalar("tag:yaml.org,2002:str", data, style="|")


yaml.add_representer(LiteralStr, _literal_representer)
yaml.add_representer(QuotedStr, _quoted_representer)

# Marked values, as 'MARKER<label>' after a single-quoted dump
_MARKED_VALUE = re.compile(r"'__(REQUIRED|OPTIONAL)__((?:[^']|'')*)'")


def required(label: str) -> str:
    """Mark a value the operator must supply. Dumped as ''  # REQUIRED: label."""
    return QuotedStr(f"__REQUIRED__{label}")


def optional(label: str) -> str:
    """Mark a value the operator may supply. Dumped as ''  # OPTIONAL: label."""
    return QuotedStr(f"__OPTIONAL__{label}")


def _marker_comment(match: re.Match[str]) -> str:
    label = match.group(2).replace("''", "'")
    return f"''  # {match.group(1)}: {label}"


def _add_marker_comments(yaml_str: str) -> str:
    """Replace marked values with empty values and inline comments."""
    return _MARKED_VALUE.sub(_marker_comment, yaml_str)


def dump_yaml(data: dict[str, Any]) -> str:
    """Dump data to a YAML string without folding long lines."""
    return _add_marker_comments(
        yaml.dump(
            data,
            default_flow_style=False,
            sort_keys=False,
            allow_unicode=True,
            width=float("inf"),
        )
    )


def _section_header(title: str, description: str) -> str:
    """Generate a section header comment block."""
    return (
        f"# =============================================================================\n"
        f"# {title}\n"
        f"# =============================================================================\n"
        f"# {description}\n"
        f"# ------------------------------------------------------------------------------\n"
    )


def dump_yaml_sections(
    sections: list[tuple[str, str, str, dict[str, Any]]],
) -> str:
    """Dump multiple YAML sections, each with a comment header.

    Args:
        sections: List of (key, title, description, data) tuples.

    Returns:
        YAML string with section headers between top-level keys.
    """
    parts: list[str] = []
    for key, title, description, data in sections:
        header = _section_header(title, description)
        yaml_str = dump_yaml({key: data})
        parts.append(header + yaml_str)
    return "\n".join(parts)


def file_header(file_type: str, config: PlatformConfig) -> str:
    """Generate the descriptive header comment block for a generated file."""
    header = f"""# =============================================================================
# Guardian Platform - {file_type.upper()} FILE
# =============================================================================
# Generated by govctl for:
#   Cloud Provider: {config.cloud_provider.value.upper()}
#   Auth Provider:  {config.auth_provider.value}
#   Environment:    {config.environment}
#   Domain:         {config.domain}
# =============================================================================
#
"""
    if file_type in ("values", "bootstrap"):
        header += """# IMPORTANT: Fill in every value marked REQUIRED and replace every YOUR_*
# placeholder before deploying.
#
"""
    return header


def dump_yaml_with_header(
    data: dict[str, Any],
    file_type: str,
    config: PlatformConfig,
) -> str:
    """Dump YAML with a descriptive header."""
    header = file_header(file_type, config)

    if file_type == "secrets":
        header += """# IMPORTANT: Fill in every value marked REQUIRED before deploying.
# Values marked OPTIONAL and some other empty values, such as the registry
# email and the AWS KMS session token, are optional.
#
# Generate random secrets with:
#   openssl rand -base64 32
#
# NOTE: For the database password, use hex encoding to avoid special
# characters (+, /, =) that break PostgreSQL connection URI parsing:
#   openssl rand -hex 32
#
# =============================================================================

"""

    return header + dump_yaml(data)
